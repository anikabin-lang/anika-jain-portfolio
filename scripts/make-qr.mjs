// Regenerates src/data/qr.js — run `node scripts/make-qr.mjs` after changing a QR target.
import QRCode from "qrcode";
import { writeFileSync } from "node:fs";

const codes = {
  // Front of the badge: GitHub profile.
  front: { text: "https://github.com/anikabin-lang", ecc: "L" },
  // Back of the badge ("Scan to visit"): the live portfolio.
  back: { text: "https://anikajain.runs-on.dev/", ecc: "M" },
};

const toPath = ({ modules }) => {
  const n = modules.size;
  let d = "";
  for (let y = 0; y < n; y++) {
    let x = 0;
    while (x < n) {
      if (!modules.get(y, x)) { x++; continue; }
      let run = 1;
      while (x + run < n && modules.get(y, x + run)) run++;
      d += `M${x} ${y}h${run}v1h-${run}z`;
      x += run;
    }
  }
  return { size: n, d };
};

let out = "// Generated by scripts/make-qr.mjs — do not edit by hand.\n";
for (const [name, { text, ecc }] of Object.entries(codes)) {
  const qr = QRCode.create(text, { errorCorrectionLevel: ecc });
  const { size, d } = toPath(qr);
  out += `export const ${name}QR = { text: ${JSON.stringify(text)}, size: ${size}, d: ${JSON.stringify(d)} };\n`;
}
writeFileSync(new URL("../src/data/qr.js", import.meta.url), out);
console.log(out.replace(/d: ".*?"/g, 'd: "…"'));
